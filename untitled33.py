import json
import numpy as np

# -------------------------------------------------
# Step 1: Load the data
# -------------------------------------------------
with open('items.json') as f:
    items = json.load(f)

with open('packages.json') as f:
    packages = json.load(f)

print(f"Loaded {len(items)} items and {len(packages)} packages")

# Create convenient mappings
item_names = [it['name'] for it in items]
name_to_idx = {name: i for i, name in enumerate(item_names)}
prices = np.array([it['price'] for it in items], dtype=int)

n_items = len(items)          # 60
n_packages = len(packages)    # 1000

# -------------------------------------------------
# Step 2: Build the linear system  A * v ≈ V
# -------------------------------------------------
# A is a 1000 × 60 matrix of 0/1 indicators
# V is the vector of measured package volumes

A = np.zeros((n_packages, n_items))
V = np.zeros(n_packages)

for p_idx, package in enumerate(packages):
    V[p_idx] = package['total_volume']
    for item_name in package['items']:
        A[p_idx, name_to_idx[item_name]] = 1

print("Design matrix shape:", A.shape)

# -------------------------------------------------
# Step 3: Estimate item volumes by Ordinary Least Squares
# -------------------------------------------------
# Solve  min ||A v - V||²
v_est = np.linalg.lstsq(A, V, rcond=None)[0]

print("\nEstimated volumes (first 10):")
for name, vol in zip(item_names[:10], v_est[:10]):
    print(f"  {name}: {vol:.3f} L")

print(f"\nMin volume: {v_est.min():.3f} L")
print(f"Max volume: {v_est.max():.3f} L")
print(f"All volumes positive? {np.all(v_est > 0)}")

# Quick residual check
residuals = V - A @ v_est
print(f"Residual std: {residuals.std():.3f}  (expected ≈ √2 ≈ 1.41)")

# -------------------------------------------------
# Step 4: Solve the 0/1 Knapsack problem
#          capacity = 40 litres, maximise price
# -------------------------------------------------
# We discretise volumes to 0.01 L precision so we can use classic DP

SCALE = 100                    # 0.01 litre resolution
vols  = np.round(v_est * SCALE).astype(int)
CAP   = 40 * SCALE             # 4000

# dp[w] = maximum price achievable with total volume ≤ w
dp = np.full(CAP + 1, -10**9)
dp[0] = 0

# take[i][w] = True if item i was taken to reach weight w
take = np.zeros((n_items, CAP + 1), dtype=bool)

for i in range(n_items):
    v = vols[i]
    p = prices[i]
    if v > CAP:
        continue
    # Work backwards so each item is used at most once
    new_dp = dp.copy()
    for w in range(CAP - v + 1):
        if dp[w] + p > new_dp[w + v]:
            new_dp[w + v] = dp[w] + p
            take[i, w + v] = True
    dp = new_dp

# -------------------------------------------------
# Step 5: Recover the optimal solution
# -------------------------------------------------
max_price = int(np.max(dp))
best_w    = int(np.argmax(dp))

print(f"\n=== OPTIMAL SOLUTION ===")
print(f"Maximum total price : {max_price}")
print(f"Total estimated volume: {best_w / SCALE:.3f} L")

# Reconstruct the list of selected items
selected = []
w = best_w
for i in range(n_items - 1, -1, -1):
    if take[i, w]:
        selected.append(item_names[i])
        w -= vols[i]

selected = sorted(selected)
print("Selected items:", selected)
print("Number of items:", len(selected))

# Verification
sum_price = sum(prices[name_to_idx[s]] for s in selected)
sum_vol   = sum(v_est[name_to_idx[s]] for s in selected)
print(f"Verification – price sum: {sum_price}")
print(f"Verification – volume sum: {sum_vol:.3f} L")

